#!/usr/bin/env python3
"""
Turns the AI-drafted angel strips in art/angel-raw/ into the angel's pixel-art sprite sheet.

    python3 scripts/art/process_angel.py            # writes the sheet + metadata
    python3 scripts/art/process_angel.py --preview  # also writes art/angel-preview.png

Same steps as process_hero.py (key out magenta, find frames, box-filter down to native size,
snap to one shared palette). Each frame is lined up on its own robe hem, so the body holds
still and the game adds the gentle hover bob with a tween; the gift then stays in the hands.

Needs Pillow. Outputs:
  src/assets/angel/angel.png         sprite sheet (cells side by side, row-major)
  src/scenes/angel/angelSheet.ts     cell size, origin, hands and animation frame ranges
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import process_hero as hero  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / 'art' / 'angel-raw'
OUT_PNG = ROOT / 'src' / 'assets' / 'angel' / 'angel.png'
OUT_TS = ROOT / 'src' / 'scenes' / 'angel' / 'angelSheet.ts'
PREVIEW = ROOT / 'art' / 'angel-preview.png'

# Halo top to robe hem of the first hover frame: source pixels → native pixels (hero is 64).
SOURCE_HEIGHT = 300
NATIVE_HEIGHT = 84
PALETTE_SIZE = 32
COLUMNS = 8
# Where the cupped hands are in the first hover frame, in source pixels.
HANDS_SOURCE = (240, 476)


@dataclass
class Strip:
    file: str
    anim: str
    frames: int


STRIPS = [
    Strip('hover.webp', 'hover', 6),
]


@dataclass
class Frame:
    img: Image.Image
    anchor_x: int
    ground_y: int


def load() -> tuple[list[Frame], dict[str, tuple[int, int]], tuple[int, int]]:
    scale = NATIVE_HEIGHT / SOURCE_HEIGHT
    frames: list[Frame] = []
    anims: dict[str, tuple[int, int]] = {}
    hands = (0, 0)
    for strip in STRIPS:
        src = Image.open(RAW / strip.file).convert('RGB')
        masks = hero.find_frames(src, strip.frames)
        start = len(frames)
        for i, m in enumerate(masks):
            img = hero.shrink(src, m, scale)
            f = Frame(img, hero.feet_anchor_x(img), hero.opaque_bounds(img)[3])
            if not frames:
                # Map the hands from source pixels into this frame, relative to its hem.
                x0 = m.getbbox()[0]
                hands = (
                    round((HANDS_SOURCE[0] - x0) * scale) - f.anchor_x,
                    round(HANDS_SOURCE[1] * scale) - f.ground_y,
                )
            frames.append(f)
        anims[strip.anim] = (start, len(frames) - 1)
    return frames, anims, hands


def pack(frames: list[Frame]) -> tuple[Image.Image, int, int, int, int]:
    b = [hero.opaque_bounds(f.img) for f in frames]
    half = max(max(f.anchor_x - bb[0], bb[2] - f.anchor_x) for f, bb in zip(frames, b)) + 1
    up = max(f.ground_y - bb[1] for f, bb in zip(frames, b))
    cell_w, cell_h = half * 2, up + 2
    rows = (len(frames) + COLUMNS - 1) // COLUMNS
    cols = min(COLUMNS, len(frames))
    sheet = Image.new('RGBA', (cell_w * cols, cell_h * rows), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        cx, cy = (i % COLUMNS) * cell_w, (i // COLUMNS) * cell_h
        sheet.alpha_composite(f.img, (cx + half - f.anchor_x, cy + up - f.ground_y))
    return sheet, cell_w, cell_h, half, up


def write_ts(cw: int, ch: int, ox: int, oy: int, hands: tuple[int, int], anims: dict[str, tuple[int, int]]) -> None:
    rows = '\n'.join(f'    {k}: {{ start: {a}, end: {b} }},' for k, (a, b) in anims.items())
    OUT_TS.write_text(
        f"""// Generated by scripts/art/process_angel.py from art/angel-raw/. Do not edit by hand.

/** Angel sprite sheet layout: equal cells, row-major, robe hem of every frame at (originX, originY). */
export const ANGEL_SHEET = {{
  frameWidth: {cw},
  frameHeight: {ch},
  originX: {ox},
  originY: {oy},
  /** Cupped hands, in native pixels from the robe hem. */
  handsX: {hands[0]},
  handsY: {hands[1]},
  anims: {{
{rows}
  }},
}} as const;
"""
    )


def write_preview(sheet: Image.Image, oy: int, ox: int, cw: int, hands: tuple[int, int]) -> None:
    zoom = 4
    out = Image.new('RGBA', (sheet.width, sheet.height * 2), (60, 52, 90, 255))
    out.paste((236, 226, 196, 255), (0, sheet.height, sheet.width, sheet.height * 2))
    for row in (0, sheet.height):
        out.alpha_composite(sheet, (0, row))
        px = out.load()
        for i in range(sheet.width // cw):
            hx, hy = i * cw + ox + hands[0], row + oy + hands[1]
            px[hx, hy] = (255, 0, 0, 255)
    out.resize((out.width * zoom, out.height * zoom), Image.NEAREST).save(PREVIEW)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--preview', action='store_true')
    args = ap.parse_args()
    hero.PALETTE_SIZE = PALETTE_SIZE
    frames, anims, hands = load()
    pal = hero.shared_palette(frames)  # type: ignore[arg-type]
    for f in frames:
        f.img = hero.snap_to_palette(f.img, pal)
    sheet, cw, ch, ox, oy = pack(frames)
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(OUT_PNG, optimize=True)
    write_ts(cw, ch, ox, oy, hands, anims)
    if args.preview:
        write_preview(sheet, oy, ox, cw, hands)
    print(f'{len(frames)} frames, cell {cw}x{ch}, hands {hands}', file=sys.stderr)


if __name__ == '__main__':
    main()
